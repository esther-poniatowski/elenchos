// Writes `src/generated/schema.ts` from the schema of a producer log that the Python package of
// Elenchos ships, `src/elenchos/schemas/findings-profile.schema.json`, so that the sources import
// the schema without reading a file at run time. The JSON file stays the only source.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL(
  "../../../src/elenchos/schemas/findings-profile.schema.json",
  import.meta.url,
);
const target = new URL("../src/generated/schema.ts", import.meta.url);
const schema = JSON.parse(readFileSync(source, "utf8"));
mkdirSync(fileURLToPath(new URL(".", target)), { recursive: true });
writeFileSync(
  target,
  "// Generated by scripts/generate-schema.mjs from findings-profile.schema.json; do not edit.\n" +
    `export const PROFILE_SCHEMA: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`,
);
